import { askLuxxAI } from '../services/ai-context.js';

const WA_CHUNK = 3400;

export const DB_HELP =
    '🗄️ *!db — Generator Database*\n' +
    '━━━━━━━━━━━━━━━━━━━━━━━\n\n' +
    '📌 *Fungsi:* Buat skema database lengkap + kode SQL + contoh API siap pakai, dengan penjelasan rapi.\n\n' +
    '📝 *Format:*\n' +
    '`!db <deskripsi proyek>`\n\n' +
    '💡 *Contoh:*\n' +
    '• `!db perpustakaan lengkap dengan peminjaman buku`\n' +
    '• `!db toko online fashion + stok + pesanan`\n' +
    '• `!db sistem absensi karyawan dengan shift`\n' +
    '• `!db aplikasi catatan keuangan pribadi`\n\n' +
    '📦 *Yang kamu dapat:*\n' +
    '1️⃣ Ringkasan & diagram relasi\n' +
    '2️⃣ Tabel lengkap (kolom, tipe, PK/FK)\n' +
    '3️⃣ SQL `CREATE TABLE` + index + constraint\n' +
    '4️⃣ Contoh query & endpoint API\n' +
    '5️⃣ Langkah setup & penjelasan singkat\n\n' +
    '_Database cloud modern — stabil, relasional, siap skala._';

function buildDbUserPrompt(brief) {
    return (
        `Buatkan desain database LENGKAP dan profesional untuk kebutuhan berikut:\n\n` +
        `"${brief}"\n\n` +
        `Stack: database relasional cloud (PostgreSQL-compatible), dengan pola API REST yang stabil.\n\n` +
        `WAJIB ikuti struktur output ini (gunakan heading persis):\n\n` +
        `📌 *JUDUL PROYEK*\n` +
        `[nama + 1 kalimat ringkasan]\n\n` +
        `🎯 *GAMBARAN UMUM*\n` +
        `[2-3 kalimat: apa yang dibuat, siapa usernya, fitur utama]\n\n` +
        `🗂️ *STRUKTUR TABEL*\n` +
        `[untuk tiap tabel: nama, fungsi, daftar kolom format → kolom | tipe | constraint | keterangan]\n\n` +
        `🔗 *RELASI & DIAGRAM*\n` +
        `[teks ERD: TabelA (1) ──< (N) TabelB, jelaskan FK]\n\n` +
        `💾 *SQL SCHEMA*\n` +
        `\`\`\`sql\n` +
        `[CREATE TABLE lengkap, PRIMARY KEY, FOREIGN KEY, UNIQUE, CHECK, INDEX, COMMENT jika perlu]\n` +
        `\`\`\`\n\n` +
        `⚡ *CONTOH API & QUERY*\n` +
        `\`\`\`sql\n` +
        `[5-8 query penting: SELECT join, INSERT, UPDATE, DELETE, agregasi]\n` +
        `\`\`\`\n` +
        `[lalu contoh endpoint REST dalam blok kode terpisah — GET/POST/PUT/DELETE dengan path & body JSON]\n\n` +
        `🛡️ *KEAMANAN & BEST PRACTICE*\n` +
        `[index yang disarankan, normalisasi, validasi data, tips performa — bullet singkat]\n\n` +
        `🚀 *LANGKAH SETUP*\n` +
        `[langkah bernomor 1-6: buat project, jalankan SQL, tes query, hubungkan app — tanpa sebut nama vendor/platform]\n\n` +
        `💡 *CATATAN*\n` +
        `[tips opsional: seed data, migrasi, backup — 2-3 poin]\n\n` +
        `Aturan:\n` +
        `- Bahasa Indonesia, teknis tapi mudah dipahami\n` +
        `- Kode SQL harus bisa dijalankan langsung (PostgreSQL dialect)\n` +
        `- Minimal 4-8 tabel sesuai kompleksitas proyek\n` +
        `- Jangan sebut nama provider/API pihak ketiga di teks penjelasan\n` +
        `- Emoji di heading saja, isi teknis tetap rapi`
    );
}

export function splitWhatsAppText(text, maxLen = WA_CHUNK) {
    if (!text || text.length <= maxLen) return [text];

    const chunks = [];
    let rest = text;

    while (rest.length > maxLen) {
        let cut = rest.lastIndexOf('\n\n', maxLen);
        if (cut < maxLen * 0.4) cut = rest.lastIndexOf('\n', maxLen);
        if (cut < maxLen * 0.3) cut = maxLen;
        chunks.push(rest.slice(0, cut).trim());
        rest = rest.slice(cut).trim();
    }
    if (rest) chunks.push(rest);
    return chunks;
}

/**
 * @param {import('@whiskeysockets/baileys').WASocket} sock
 */
export async function handleDbCommand({ sock, from, sender, isGroup, isAdmin, msg, args }) {
    const brief = args.join(' ').trim();
    if (!brief) {
        return sock.sendMessage(from, { text: DB_HELP }, { quoted: msg });
    }

    await sock.sendMessage(from, {
        text:
            `🗄️ *LuxxDB Generator*\n` +
            `━━━━━━━━━━━━━━━━━━━━━━━\n\n` +
            `📋 *Proyek:* ${brief}\n\n` +
            `⏳ Lagi susun skema, SQL, dan API-nya...\n` +
            `_Biasanya 15–40 detik ya_ ✨`
    }, { quoted: msg });

    try {
        const prompt = buildDbUserPrompt(brief);
        const raw = await askLuxxAI(sock, from, sender, isGroup, isAdmin, prompt, 'db');

        if (!raw?.trim()) {
            return sock.sendMessage(from, {
                text: '❌ Gagal generate database. Coba lagi atau sederhanakan deskripsinya.'
            }, { quoted: msg });
        }

        const header =
            `✅ *DATABASE SIAP!*\n` +
            `━━━━━━━━━━━━━━━━━━━━━━━\n` +
            `📋 *Request:* ${brief}\n` +
            `🤖 _Generated by LuxxBot_\n\n`;

        const parts = splitWhatsAppText(raw);
        for (let i = 0; i < parts.length; i++) {
            const prefix = i === 0 ? header : `📄 *Lanjutan (${i + 1}/${parts.length})*\n\n`;
            await sock.sendMessage(from, { text: prefix + parts[i] }, i === 0 ? { quoted: msg } : {});
            if (i < parts.length - 1) await new Promise((r) => setTimeout(r, 800));
        }

        if (parts.length === 1) {
            await sock.sendMessage(from, {
                text:
                    `━━━━━━━━━━━━━━━━━━━━━━━\n` +
                    `💬 Mau revisi? Ketik:\n` +
                    `\`!db ${brief} + tambah fitur ...\`\n\n` +
                    `_Atau pakai \`!coding\` buat kode aplikasinya_ 🚀`
            });
        }
    } catch (e) {
        console.error('DB CMD ERROR:', e?.message || e);
        await sock.sendMessage(from, {
            text: '❌ Gagal memproses permintaan database. Coba lagi sebentar.'
        }, { quoted: msg });
    }
}